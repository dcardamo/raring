#!/usr/bin/env node
// Writes every vector copy of the brand mark: a readiness gauge whose ink
// progress ends at a green marker. The arcs stop at a ring cut around the
// marker and are drawn as filled outlines, so the one-colour notification and
// themed-icon copies keep the gap without masks.
// Then regenerate the raster sizes: cd app && cargo tauri icon src-tauri/icons/icon.json
import {writeFileSync} from 'node:fs';
import {dirname, join} from 'node:path';
import {fileURLToPath} from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const cx = 256, cy = 279, R = 156, stroke = 46, markerR = 38, cutR = 48;
const start = 135, end = 405, at = start + 270 * 0.72;
const Ro = R + stroke / 2, Ri = R - stroke / 2, cap = stroke / 2;
const colors = {tile: '#111317', track: '#343A43', ink: '#F4F1EA', marker: '#60D3A0'};

const rad = d => d * Math.PI / 180, n = v => +v.toFixed(2);
const polar = (r, d) => `${n(cx + r * Math.cos(rad(d)))} ${n(cy + r * Math.sin(rad(d)))}`;
// Degrees either side of the marker where a circle of radius r meets the cut.
const meet = r => Math.acos((r * r + R * R - cutR * cutR) / (2 * r * R)) * 180 / Math.PI;
const flag = (a, b) => (b - a > 180 ? 1 : 0);

const progress = (() => {
  const o = at - meet(Ro), i = at - meet(Ri);
  return `M${polar(Ro, start)}A${Ro} ${Ro} 0 ${flag(start, o)} 1 ${polar(Ro, o)}` +
    `A${cutR} ${cutR} 0 0 0 ${polar(Ri, i)}A${Ri} ${Ri} 0 ${flag(start, i)} 0 ${polar(Ri, start)}` +
    `A${cap} ${cap} 0 0 1 ${polar(Ro, start)}Z`;
})();
const track = (() => {
  const o = at + meet(Ro), i = at + meet(Ri);
  return `M${polar(Ro, o)}A${Ro} ${Ro} 0 ${flag(o, end)} 1 ${polar(Ro, end)}` +
    `A${cap} ${cap} 0 0 1 ${polar(Ri, end)}A${Ri} ${Ri} 0 ${flag(i, end)} 0 ${polar(Ri, i)}` +
    `A${cutR} ${cutR} 0 0 0 ${polar(Ro, o)}Z`;
})();
const [mx, my] = polar(R, at).split(' ').map(Number);
const marker = `M${n(mx - markerR)} ${my}a${markerR} ${markerR} 0 1 0 ${2 * markerR} 0a${markerR} ${markerR} 0 1 0 ${-2 * markerR} 0Z`;

const mark = (ink, trackColor, markerColor, trackOpacity = '') =>
  `<path d="${progress}" fill="${ink}"/>\n  <path d="${track}" fill="${trackColor}"${trackOpacity}/>\n  <path d="${marker}" fill="${markerColor}"/>`;
const svg = body => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512">\n  ${body}\n</svg>\n`;

// Adaptive-icon layers are 108 dp; launchers may mask all but the central 66 dp circle.
const outline = [...Array(271).keys()].map(k => Math.hypot(cx + Ro * Math.cos(rad(start + k)) - 256, cy + Ro * Math.sin(rad(start + k)) - 256));
const farthest = Math.max(...outline, Math.hypot(mx - 256, my - 256) + markerR);
const scale = n((512 * 31 / 108) / farthest);
const fit = body => `<g transform="translate(256 256) scale(${scale}) translate(-256 -256)">\n  ${body}\n  </g>`;

const full = svg(`<rect width="512" height="512" rx="112" fill="${colors.tile}"/>\n  ${mark(colors.ink, colors.track, colors.marker)}`);
for (const file of ['app/src-tauri/icons/raring.svg', 'app/public/favicon.svg', 'site/assets/icon.svg']) writeFileSync(join(root, file), full);
writeFileSync(join(root, 'app/src-tauri/icons/raring-foreground.svg'), svg(fit(mark(colors.ink, colors.track, colors.marker))));
writeFileSync(join(root, 'app/src-tauri/icons/raring-monochrome.svg'), svg(fit(mark('#FFF', '#FFF', '#FFF', ' fill-opacity=".4"'))));

writeFileSync(join(root, 'app/src/lib/components/BrandMark.svelte'),
  `<!-- Generated by scripts/brand-icon.mjs. -->\n<svg class="brand-mark" width="96" height="96" viewBox="56 56 400 400" aria-hidden="true">` +
  `<path d="${progress}" fill="var(--ink)"/><path d="${track}" fill="var(--chart-track)"/><path d="${marker}" fill="var(--good)"/></svg>\n`);

// Notification small icon: Android tints it one colour, so the track keeps only a lower alpha.
const vector = (d, alpha = '') => `    <path android:fillColor="#FFFFFFFF"${alpha} android:pathData="${d}"/>`;
writeFileSync(join(root, 'app/src-tauri/gen/android/app/src/main/res/drawable/ic_notification.xml'), `<?xml version="1.0" encoding="utf-8"?>
<!-- The app mark, generated by scripts/brand-icon.mjs. Android tints it. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp" android:height="24dp" android:viewportWidth="440" android:viewportHeight="440">
  <group android:translateX="-36" android:translateY="-36">
${vector(progress)}
${vector(track, ' android:fillAlpha="0.4"')}
${vector(marker)}
  </group>
</vector>
`);
